import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { execFileSync } from 'node:child_process';

const repoRoot = process.cwd();
const editorRoot = resolve(repoRoot, 'apps/mobile-editor');
const outputHtml = resolve(repoRoot, 'apps/mobile/assets/mobile-editor/index.html');
const outputModule = resolve(repoRoot, 'apps/mobile/assets/mobile-editor/index.ts');

execFileSync('npm', ['run', 'build'], { cwd: editorRoot, stdio: 'inherit' });
if (!existsSync(outputHtml)) throw new Error(`Mobile editor build did not produce ${outputHtml}`);

const html = readFileSync(outputHtml, 'utf8');
if (!html.includes('<div id="root"></div>') || /<script[^>]+src=|<link[^>]+stylesheet[^>]+href=/.test(html)) {
  throw new Error('Mobile editor output is not self-contained. Expected inline HTML, CSS, and JavaScript.');
}
if (html.indexOf('<div id="root"></div>') > html.indexOf('<script>')) {
  throw new Error('Mobile editor output must initialize after the root element.');
}

writeFileSync(outputModule, `// Generated by npm run build:mobile-editor. Do not edit.\nexport const MOBILE_EDITOR_HTML = ${JSON.stringify(html)} as const;\n`);
console.log(`Generated ${outputModule} (${html.length} characters).`);
